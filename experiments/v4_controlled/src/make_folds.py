#!/usr/bin/env python3
"""
Clean Development Split: Stratified Study-Proxy 5-Fold Partitioning
Location: experiments/v4_controlled/src/make_folds.py

Partitions the 1,224 clean development scans into 5 stratified folds
using Component 8 (Study-Proxy Cluster) to ensure zero scan-level leakage.

Outputs:
  experiments/v4_controlled/data/folds.csv
  experiments/v4_controlled/data/grouping_specification.json
"""

import os
import json
import pandas as pd
import numpy as np
from sklearn.model_selection import StratifiedGroupKFold

MANIFEST_PATH = "data/authoritative_manifest.csv"
OUTPUT_FOLDS_CSV = "experiments/v4_controlled/data/folds.csv"
OUTPUT_SPEC_JSON = "experiments/v4_controlled/data/grouping_specification.json"

def create_folds():
    print("=" * 70)
    print("PHASE 1: CREATING STRATIFIED STUDY-PROXY 5-FOLD PARTITION")
    print("=" * 70)

    df = pd.read_csv(MANIFEST_PATH)
    train_df = df[df["split"] == "Train"].copy().reset_index(drop=True)
    print(f"Total clean development scans: {len(train_df)}")
    print(f"Class breakdown: UF={int((train_df['class_label'] == 'UF').sum())}, NUF={int((train_df['class_label'] == 'NUF').sum())}")

    # Extract study-proxy grouping (Component 8 of DICOM UID)
    stems = train_df["filename"].str.replace(".jpg", "", regex=False)
    parts = stems.str.split(".", expand=True)
    train_df["study_proxy_group"] = parts[8]
    train_df["source_stem"] = stems

    # Numerical label: 0 for UF, 1 for NUF (consistent with UteroScan convention)
    # We will also record label_name
    train_df["target_idx"] = (train_df["class_label"] == "NUF").astype(int) # 0=UF, 1=NUF

    sgkf = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42)
    train_df["fold"] = -1

    for fold_idx, (train_idx, val_idx) in enumerate(sgkf.split(train_df, train_df["target_idx"], groups=train_df["study_proxy_group"])):
        train_df.loc[val_idx, "fold"] = fold_idx

    # Assertions
    assert (train_df["fold"] == -1).sum() == 0, "Error: Some scans were not assigned a fold!"
    assert len(train_df) == 1224, f"Expected 1,224 scans, got {len(train_df)}"

    # Check for group leakage
    for f in range(5):
        val_groups = set(train_df[train_df["fold"] == f]["study_proxy_group"])
        train_groups = set(train_df[train_df["fold"] != f]["study_proxy_group"])
        overlap = val_groups.intersection(train_groups)
        assert len(overlap) == 0, f"LEAKAGE DETECTED in Fold {f}: {len(overlap)} groups overlap!"

    print("\n[VERIFIED] 0% study-proxy group leakage across all 5 folds.")

    fold_stats = []
    for f in range(5):
        sub = train_df[train_df["fold"] == f]
        uf_count = int((sub["class_label"] == "UF").sum())
        nuf_count = int((sub["class_label"] == "NUF").sum())
        groups_count = sub["study_proxy_group"].nunique()
        fold_stats.append({
            "fold": f,
            "total_scans": len(sub),
            "uf_scans": uf_count,
            "nuf_scans": nuf_count,
            "unique_study_proxy_groups": groups_count,
            "uf_proportion": round(uf_count / len(sub), 4)
        })
        print(f"  Fold {f}: {len(sub):3d} scans ({uf_count:3d} UF, {nuf_count:3d} NUF, {groups_count:3d} groups, UF%={uf_count/len(sub)*100:.1f}%)")

    # Save CSV
    train_df.to_csv(OUTPUT_FOLDS_CSV, index=False)
    print(f"\n[SAVED] Folds manifest -> {OUTPUT_FOLDS_CSV}")

    # Document Grouping Specification & Limitations
    grouping_spec = {
        "dataset_name": "UteroScan Clean Development Cohort (1,224 scans)",
        "partition_strategy": "StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42)",
        "group_key": "Component 8 of Medical Connections DICOM SOP Instance UID",
        "total_unique_study_proxy_groups": int(train_df["study_proxy_group"].nunique()),
        "total_scans": len(train_df),
        "leakage_verification": "0 group overlaps between train and val folds across all 5 folds",
        "fold_distributions": fold_stats,
        "methodological_limitations_and_disclaimer": (
            "DISCLAIMER ON PATIENT INDEPENDENCE: Component 8 represents the study/series-level "
            "grouping generated by Medical Connections DICOM de-identification software. Scans sharing "
            "the same Component 8 are guaranteed to be from the same imaging study/series and are strictly "
            "kept in the same fold to prevent intra-study scan-level leakage. However, because the public "
            "Mendeley repository does not provide demographic patient IDs, we cannot guarantee that two "
            "different Component 8 values never belong to the same patient examined across multiple appointments. "
            "Therefore, this evaluation is scientifically defined as 'Study-Proxy Clustered 5-Fold Cross-Validation', "
            "NOT guaranteed patient-level separation."
        )
    }

    with open(OUTPUT_SPEC_JSON, "w", encoding="utf-8") as f:
        json.dump(grouping_spec, f, indent=2)
    print(f"[SAVED] Grouping specification JSON -> {OUTPUT_SPEC_JSON}")

if __name__ == "__main__":
    create_folds()
